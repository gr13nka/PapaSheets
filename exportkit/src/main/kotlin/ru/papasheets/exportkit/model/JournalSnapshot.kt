package ru.papasheets.exportkit.model

/**
 * Плоский снимок журнала-месяца для экспорта. Раскладка (порядок подрядчиков-колонок, набор полей,
 * разбиение записей на дни и строки внутри дня) уже решена вызывающей стороной — app/domain/export
 * строит его поверх той же раскладки, что и матрица ([ru.papasheets.domain.buildGridModel]), не
 * дублируя логику. exportkit ничего не знает о Room/UUID/Android — отсюда его быстрые JVM-тесты формата.
 */
class JournalSnapshot(
    /** Заголовок журнала, например «Июль 2026» — идёт и в имя листа xlsx, и в имя файла. */
    val title: String,
    /** Порядок = порядок групп колонок в xlsx слева направо и порядок подрядчика в CSV. */
    val contractors: List<SnapshotContractor>,
    /**
     * Подколонки внутри группы каждого подрядчика, кроме фото-колонки Ф: строка 2 шапки xlsx,
     * колонки после «Подрядчик» в CSV и порядок значений в [SnapshotCell.values].
     * Список может быть и пустым — пользователю не запрещено заархивировать все поля.
     */
    val fields: List<SnapshotField>,
    /** Дни строго по возрастанию даты — бумажный журнал читается сверху вниз, вне зависимости от сортировки в UI. */
    val days: List<SnapshotDay>,
)

/**
 * Одна подколонка группы подрядчика. Геометрия здесь уже в единицах Excel, а не в dp: перевод —
 * дело вызывающей стороны ([ru.papasheets.exportkit.xlsx.Widths]), чтобы модель снимка не зависела
 * от того, как поле выглядит на экране.
 */
class SnapshotField(
    /** Подпись во второй строке шапки: «Л», «ВИД РАБОТ», «Объём». */
    val title: String,
    /** Ширина колонки в символьных единицах Excel. */
    val widthChars: Double,
    /** Перенос строк в ячейке (стиль `STYLE_WRAP`); от него же зависит оценка высоты строк с фото. */
    val wrap: Boolean,
)

class SnapshotContractor(val name: String)

class SnapshotDay(
    /** Уже отформатированная дата, например «17.07» — и колонка A в xlsx, и поле «Дата» в CSV. */
    val dateLabel: String,
    /** Строки этого дня в порядке отображения; пустых дней в списке нет. */
    val rows: List<SnapshotRow>,
)

class SnapshotRow(
    /** Ровно contractors.size элементов; null — пустой слот (в xlsx — пустые ячейки, в CSV строка не создаётся). */
    val cells: List<SnapshotCell?>,
)

class SnapshotCell(
    /**
     * Значения полей — ровно [JournalSnapshot.fields].size элементов в том же порядке.
     * Пустое значение задаётся `""`, а не пропуском элемента: позиция в списке и есть привязка
     * к полю, поэтому короткий список сдвинул бы значения ячейки в чужие колонки листа.
     */
    val values: List<String>,
    /** Ключ фото для [PhotoBytesProvider] или null, если фото ещё нет. */
    val photoId: String?,
)
