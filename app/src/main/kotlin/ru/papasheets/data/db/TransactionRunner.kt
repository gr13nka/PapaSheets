package ru.papasheets.data.db

/**
 * Единая Room-транзакция поверх нескольких репозиториев — нужна только восстановлению бэкапа (M7):
 * набор upsert'ов по разным таблицам (журналы/подрядчики/пресеты/фото/записи) должен примениться
 * весь или не примениться вовсе. Не выставляет наружу ни [AppDatabase], ни отдельные DAO — вызывающая
 * сторона (домен) видит только эту одну операцию.
 */
interface TransactionRunner {
    suspend fun <T> run(block: suspend () -> T): T
}
