package ru.papasheets.ui.common

import androidx.compose.foundation.layout.imePadding
import androidx.compose.foundation.layout.navigationBarsPadding
import androidx.compose.ui.Modifier

/**
 * Отступ формы под клавиатуру и системную панель жестов.
 *
 * Окно приложения edge-to-edge, то есть содержимое рисуется под системными панелями и под
 * клавиатурой — поджиматься обязано оно само. Правило вынесено сюда, а не расставлено по экранам:
 * его отсутствие не видно на глаз при разработке (на большом экране эмулятора всё влезает) и
 * обнаруживается уже на телефоне, когда набираемый текст оказывается под клавиатурой.
 *
 * **Одного этого модификатора мало.** Он лишь сжимает форму до свободной высоты; чтобы поле под
 * фокусом можно было ПОДНЯТЬ над клавиатурой, форма обязана быть прокручиваемой — иначе низ просто
 * обрежется. Применять вместе с `verticalScroll`.
 */
fun Modifier.formInsets(): Modifier = imePadding().navigationBarsPadding()
