package ru.papasheets.matrixgrid

/**
 * Уровень детализации матрицы — дискретная функция масштаба (см. spec, риск 3: TextMeasurer — главная
 * цена Canvas). Ярус решает, что вообще рисуется и измеряется на данном зуме; промежуточный масштаб
 * внутри яруса добирается canvas-трансформом в рендерере, поэтому смена самого зума ярус не двигает,
 * пока не пересечена граница. Границы ярусов и пределы зума живут только здесь — единственный источник.
 */
internal enum class Lod {
    /** Детальный: фото-превью, код локации и 2–3 строки вида работ. Зум ≥ [DETAIL_MIN_ZOOM]. */
    LOD0,

    /** Компактный: микро фото-превью и код локации; вид работ не рисуется и не измеряется. */
    LOD1,

    /** «Картина месяца»: заполненная ячейка — сплошной блок цвета подрядчика, без битмапов и текста ячеек. */
    LOD2;

    companion object {
        /** Нижняя граница зума яруса LOD0. */
        const val DETAIL_MIN_ZOOM = 0.7f

        /** Нижняя граница зума яруса LOD1 (ниже — LOD2). */
        const val COMPACT_MIN_ZOOM = 0.3f

        /** Верхний предел пинч-зума: дальше приближать смысла нет (ячейка и так крупнее экранной). */
        const val MAX_ZOOM = 2.0f

        /** Абсолютный пол зума — страховка от нуля при вырожденном/пустом мире. */
        const val MIN_ZOOM_FLOOR = 0.02f

        fun forZoom(zoom: Float): Lod = when {
            zoom >= DETAIL_MIN_ZOOM -> LOD0
            zoom >= COMPACT_MIN_ZOOM -> LOD1
            else -> LOD2
        }
    }
}
