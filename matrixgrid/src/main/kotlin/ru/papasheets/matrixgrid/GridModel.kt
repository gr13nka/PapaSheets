package ru.papasheets.matrixgrid

/**
 * Иммутабельная модель матрицы «дата × подрядчик» — единственный вход данных для [MatrixView].
 *
 * Модуль matrixgrid ничего не знает о Room, файлах и Coil: приходит готовая раскладка
 * (строится в app/GridModelBuilder), картинки поступают через [ThumbnailSource] по ключу.
 * Смена экземпляра модели — единственный повод для рекомпозиции матрицы и сброса кэшей рендерера
 * (инвалидация идёт по идентичности экземпляра, см. [CellTextCache]); pan/zoom живут в [MatrixState]
 * и до рекомпозиции не дотрагиваются.
 */
class GridModel(
    /** Порядок списка = порядок групп колонок слева направо. */
    val contractors: List<ContractorColumn>,
    /**
     * Подколонки внутри КАЖДОЙ группы подрядчика, после фото-подколонки Ф.
     * Набор один на всю матрицу, а не свой у каждой группы: именно поэтому ширина группы —
     * константа модели, и «координата → группа» остаётся делением за O(1) (см. [MatrixGeometry]).
     */
    val fields: List<GridField>,
    /** Все строки в порядке отображения (сортировку по дате решает builder). */
    val rows: List<GridRow>,
)

/**
 * Описание одной подколонки внутри группы подрядчика: чем её заполняют, насколько она широкая и на
 * каких ярусах детализации её вообще видно.
 */
class GridField(
    /**
     * Стабильный ключ поля. Служит ключом кэша статических подписей шапки — в отличие от [title],
     * который пользователь может задать одинаковым у разных полей.
     */
    val id: String,
    /** Подпись во второй строке шапки: «Л», «ВИД РАБОТ», «Объём». */
    val title: String,
    val widthDp: Int,
    /**
     * Потолок строк текста на LOD0. 0 = без ограничения: строка матрицы растёт под текст,
     * чтобы значение было видно целиком (см. [RowMetrics]).
     */
    val maxLines: Int,
    /** Рисуется ли на компактном ярусе LOD1, где места хватает лишь на самое важное. */
    val showAtCompactLod: Boolean,
)

class ContractorColumn(
    val id: String,
    val name: String,
    /** Короткое имя для шапки на сильном отдалении (LOD2). */
    val shortName: String,
    /** Индекс в палитре модуля (см. [ContractorPalette]) — цвет блоков LOD2 и тонировки ячеек. */
    val colorIndex: Int,
    /** Архивный подрядчик, оставленный колонкой только из-за записей в этом журнале — имя в шапке приглушено. */
    val isArchived: Boolean = false,
)

class GridRow(
    val dateEpochDay: Long,
    /** Подпись даты в закреплённой колонке, например «17 июл» (LOD0/LOD1); рисуется только при [isFirstOfDay]. */
    val dayLabel: String,
    /** Только число дня, например «17» — компактная подпись колонки дат на LOD2 («картина месяца»). */
    val dayNumber: String,
    /** Первая строка блока дня: рисует подпись даты и верхнюю границу-разделитель дня. */
    val isFirstOfDay: Boolean,
    /** Ровно contractors.size элементов; null = пустой слот (тап по нему = создание записи). */
    val cells: List<GridCell?>,
)

/**
 * Сколько превью помещается в одну Ф-подколонку рядом — и, значит, сколько фото у записи имеет смысл.
 * Совпадает с числом слотов в схеме записи; матрица о самой схеме не знает, но потолок один.
 */
const val MAX_PHOTOS_PER_CELL = 2

class GridCell(
    val recordId: String,
    /**
     * Ключи превью для [ThumbnailSource] (photoId) по порядку; пустой список — фото ещё нет.
     * Все они делят одну Ф-подколонку: два превью рисуются рядом внутри неё, а не расширяют группу.
     * Ширина группы — константа модели, от которой зависит вся виртуализация по X (см.
     * [MatrixGeometry]), и ставить её в зависимость от числа фото в конкретной записи нельзя.
     */
    val thumbKeys: List<String>,
    /**
     * Значения полей — ровно [GridModel.fields].size элементов в том же порядке.
     * Пустое значение задаётся `""`, а не пропуском элемента: позиция в списке и есть привязка
     * к полю, поэтому короткий список сдвинул бы все значения ячейки в чужие подколонки.
     */
    val values: List<String>,
)

/**
 * Потолок строк текста для поля без собственного ограничения ([GridField.maxLines] == 0).
 * Без него одна вставленная «простыня» растянула бы строку матрицы на весь мир.
 */
internal const val LINE_CAP = 20

/** Сколько строк текста измерять для этого поля на LOD0. */
internal fun GridField.lineCap(): Int = if (maxLines <= 0) LINE_CAP else maxLines
